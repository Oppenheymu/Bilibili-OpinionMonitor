/** 判断单个关键词是否应被过滤（代码层二次校验） */
export function 是否停用词(词: string): boolean {
    const 清理 = 词.trim();
    if (!清理) return true;
    if (清理.length <= 1) return true; // 单字
    if (清理.length > 20) return true; // 长句摘要
    if (/^[\d\s\p{P}\p{S}]+$/u.test(清理)) return true; // 纯数字/标点/符号
    return 停用词集合.has(清理);
}
